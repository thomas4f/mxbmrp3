#!/usr/bin/env bash
# ============================================================================
# tools/i18n/pot.sh [--update]
# The translation template: every TR()/TRC()/N_()/NC_() string in the plugin's
# source, extracted by GNU xgettext into mxbmrp3_data/languages/template.pot.
# That file is what a translator opens in Poedit (or merges into their .po with
# msgmerge) -- see mxbmrp3_data/languages/README.md.
#
#   tools/i18n/pot.sh            check: fail when template.pot is out of date
#   tools/i18n/pot.sh --update   rewrite it
#
# Standard tooling on purpose (AGENTS.md, "Reach for standard tooling"): xgettext
# already parses C++ string literals, contexts and TRANSLATORS comments; a
# homemade extractor would be the first thing to drift.
#
# STABLE OUTPUT. --no-location drops the file:line references, which would move
# on every unrelated edit and turn this gate red for a change that added no
# string. The creation date is pinned for the same reason. Entries are sorted, so
# moving code between files does not reorder the template.
#
# Also checks every shipped strings.po with msgfmt --check (format strings,
# header) -- the same check Poedit runs on save -- and that no translated text
# is copied with strcpy_s: a pack's line can be longer than any English one, and
# an overlong strcpy_s source closes the game on MSVC. snprintf("%s") truncates.
# ============================================================================
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
POT="${ROOT}/mxbmrp3_data/languages/template.pot"

if UNSAFE="$(cd "$ROOT" && grep -rlPz --include='*.cpp' --include='*.h' --exclude-dir=vendor \
        'strcpy_s\([^;]*?(\bTRC?\(|I18n::)[^;]*?\);' mxbmrp3)"; then
    echo "FAIL: strcpy_s of translated text (use snprintf(buf, sizeof(buf), \"%s\", ...)) in:"
    echo "$UNSAFE" | sed 's/^/  /'
    exit 1
fi

for tool in xgettext msgfmt; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        echo "SKIP: $tool not installed (apt install gettext, or ./tools/install_deps.sh)"
        exit 3
    fi
done

TMP="$(mktemp)"
trap 'rm -f "$TMP" "$TMP.files"' EXIT

( cd "$ROOT" && find mxbmrp3 -path mxbmrp3/vendor -prune -o \( -name '*.cpp' -o -name '*.h' -o -name '*.inc' \) -print \
    | LC_ALL=C sort ) > "$TMP.files"

( cd "$ROOT" && xgettext --language=C++ --from-code=UTF-8 \
    --keyword= --keyword=TR --keyword=TRC:1c,2 --keyword=N_ --keyword=NC_:1c,2 \
    --add-comments=TRANSLATORS: --no-location --sort-output --no-wrap \
    --package-name=mxbmrp3 --msgid-bugs-address="https://github.com/thomas4f/mxbmrp3/issues" \
    --files-from="$TMP.files" --output=- ) \
  | sed -e '1,4d' \
  | sed -e '1i # mxbmrp3 translation template, generated by tools/i18n/pot.sh - do not edit.\n# To translate: see README.md in this folder.' \
        -e 's/^"POT-Creation-Date: .*\\n"$/"POT-Creation-Date: 2026-01-01 00:00+0000\\n"/' \
        -e 's/^"Content-Type: text\/plain; charset=CHARSET\\n"$/"Content-Type: text\/plain; charset=UTF-8\\n"/' \
  > "$TMP"

# Each settings label's room, measured in the real panel by i18n_limits_test
# (tests/fixtures/i18n_limits.json), goes in as "#. max N characters" above
# its msgid: Poedit shows it to the translator, and the plugin reads it back at
# load and shows English for a longer line (core/i18n.cpp). A limit whose label
# is no longer in the source (renamed or removed) fails here, since the
# integration test that re-measures it does not run on every change.
python3 - "$TMP" "${ROOT}/tests/fixtures/i18n_limits.json" <<'PY'
import json, sys
pot, limits = sys.argv[1], json.load(open(sys.argv[2], encoding="utf-8"))
entries = open(pot, encoding="utf-8").read().split("\n\n")
known = set()
for i, entry in enumerate(entries):
    lines = entry.split("\n")
    if any(l.startswith("msgctxt ") for l in lines):
        continue
    ids = [l[7:-1].replace('\\"', '"').replace("\\\\", "\\") for l in lines if l.startswith('msgid "')]
    if ids and ids[0] in limits:
        known.add(ids[0])
        entries[i] = "#. max %d characters\n" % limits[ids[0]] + entry
open(pot, "w", encoding="utf-8").write("\n\n".join(entries))
stale = sorted(set(limits) - known)
if stale:
    print("FAIL: tests/fixtures/i18n_limits.json names %d label(s) no longer in the source:" % len(stale))
    for k in stale[:20]:
        print("      " + k)
    print("      Rerun i18n_limits_test, copy its i18n_limits.new.json over the fixture, then pot.sh --update.")
    sys.exit(1)
PY

status=0
if [[ "${1:-}" == "--update" ]]; then
    cp "$TMP" "$POT"
    echo "wrote ${POT#"$ROOT"/} ($(grep -c '^msgid ' "$POT") entries, header included)"
elif ! diff -q "$TMP" "$POT" >/dev/null 2>&1; then
    echo "FAIL: mxbmrp3_data/languages/template.pot is out of date with the source."
    echo "      Run tools/i18n/pot.sh --update and commit the result. Difference:"
    diff -u "$POT" "$TMP" | head -40 || true
    status=1
else
    echo "template.pot is current ($(grep -c '^msgid ' "$POT") entries, header included)"
fi

shopt -s nullglob
for po in "$ROOT"/mxbmrp3_data/languages/*/strings.po; do
    if ! msgfmt --check --statistics -o /dev/null "$po"; then
        echo "FAIL: ${po#"$ROOT"/} does not pass msgfmt --check"
        status=1
    fi
done
exit $status
