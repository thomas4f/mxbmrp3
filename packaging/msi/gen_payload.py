"""Generate payload.wxs: the plugin payload, once per game, as WiX components.

    gen_payload.py <staging dir> <out .wxs>

The staging tree is the same one makensis packages (release.yml's
build-release job: the three .dlo files, mxbmrp3_data\\, LICENSE and
THIRD_PARTY_LICENSES.md), so both installers ship the same bytes. The whole
mxbmrp3_data tree goes to every game by walking it, not by listing it, so a
new data subfolder cannot reach fewer than all three games. (NSIS's
INSTALL_GAME_FILES lists its subfolders instead, and so leaves out the
folder's own README.txt, the "do not edit" note, which this one installs.)

Why generated rather than WiX's <Files> glob: <Files> derives its ids from the
source path alone, and the same payload under three games would collide. Ids
here are per game and positional over a SORTED walk, so the same staging tree
always gives the same ids (WiX derives each component GUID from its directory
and file, so they are stable between builds too).

The licence notices go INSIDE mxbmrp3_data, beside the payload they cover, for
the reasons packaging/mxbmrp3.nsi gives at the same step.
"""
import os
import sys
from xml.sax.saxutils import quoteattr

GAMES = [("MXB", "mxbmrp3.dlo"), ("GPB", "mxbmrp3_gpb.dlo"), ("KRP", "mxbmrp3_krp.dlo")]


def main():
    stage, out = os.path.abspath(sys.argv[1]), sys.argv[2]
    data = os.path.join(stage, "mxbmrp3_data")
    for need in [dlo for _, dlo in GAMES] + ["LICENSE", "THIRD_PARTY_LICENSES.md", "mxbmrp3_data"]:
        if not os.path.exists(os.path.join(stage, need)):
            sys.exit("staging is missing %s" % need)

    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- GENERATED by packaging/msi/gen_payload.py. Do not edit. -->",
             '<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">', "<Fragment>"]
    total = 0
    for key, dlo in GAMES:
        n = 0
        dirs = {"": key + "DATA"}
        dir_xml, comp_xml = [], []
        for root, subdirs, files in os.walk(data):
            subdirs.sort()
            rel = os.path.relpath(root, data)
            rel = "" if rel == "." else rel
            for d in subdirs:
                child = os.path.join(rel, d) if rel else d
                n += 1
                dirs[child] = "%sD%d" % (key, n)
                dir_xml.append('<DirectoryRef Id="%s"><Directory Id="%s" Name=%s /></DirectoryRef>'
                               % (dirs[rel], dirs[child], quoteattr(d)))
            for f in sorted(files):
                n += 1
                comp_xml.append('<Component Id="%sC%d" Directory="%s" Bitness="always64">'
                                '<File Id="%sF%d" Source=%s KeyPath="yes" /></Component>'
                                % (key, n, dirs[rel], key, n, quoteattr(os.path.join(root, f))))
        lines += dir_xml
        lines.append('<ComponentGroup Id="%sPayload">' % key)
        lines.append('<Component Id="%sDlo" Directory="%sPLUGINS" Bitness="always64">'
                     '<File Id="%sDlo" Source=%s KeyPath="yes" /></Component>'
                     % (key, key, key, quoteattr(os.path.join(stage, dlo))))
        for lic in ("LICENSE", "THIRD_PARTY_LICENSES.md"):
            n += 1
            lines.append('<Component Id="%sC%d" Directory="%sDATA" Bitness="always64">'
                         '<File Id="%sF%d" Source=%s KeyPath="yes" /></Component>'
                         % (key, n, key, key, n, quoteattr(os.path.join(stage, lic))))
        lines += comp_xml
        lines.append("</ComponentGroup>")
        total = n + 1
    lines += ["</Fragment>", "</Wix>"]
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("%s: %d files per game" % (out, total))


if __name__ == "__main__":
    main()
